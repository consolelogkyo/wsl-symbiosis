import { useRef, useState } from "react";
import { CheckCircle2, Loader2, Play } from "lucide-react";
import { InfoTip } from "../InfoTip";
import { type DbColumn, type DbKind, type DbQueryResult, dbExecuteSql } from "../../lib/docker";
import { errorMessage } from "../../lib/wsl";
import { BTN_GHOST, BTN_PRIMARY } from "../../lib/ui";
import { ErrorBox } from "./common";

interface Props {
  distro: string;
  containerId: string;
  kind: DbKind;
  /** Table selected on the left (templates use it). */
  table: string | null;
  columns: DbColumn[];
  /** Something may have changed (DDL, inserts): refresh the table list. */
  onChanged: () => void;
}

function quote(kind: DbKind, name: string): string {
  const mysql = kind === "mysql" || kind === "mariadb";
  return name
    .split(".")
    .map((part) => (mysql ? `\`${part}\`` : /^[a-z_][a-z0-9_]*$/.test(part) ? part : `"${part}"`))
    .join(".");
}

function templates(kind: DbKind, table: string | null, columns: DbColumn[]): { label: string; sql: string }[] {
  if (kind === "redis") {
    return [
      { label: "Listar chaves", sql: "KEYS *" },
      { label: "Ler uma chave", sql: "GET minha-chave" },
      { label: "Guardar texto", sql: 'SET minha-chave "olá"' },
      { label: "Contador", sql: "INCR visitas" },
      { label: "Tempo para expirar", sql: "TTL minha-chave" },
    ];
  }
  const mysql = kind === "mysql" || kind === "mariadb";
  const t = table ? quote(kind, table) : mysql ? "`minha_tabela`" : "minha_tabela";
  const editable = columns.filter((c) => !c.isIdentity && !c.defaultValue);
  const cols = editable.length > 0 ? editable : columns.filter((c) => !c.isIdentity);
  return [
    { label: "Ver as linhas", sql: `SELECT *\nFROM ${t}\nLIMIT 100;` },
    { label: "Contar linhas", sql: `SELECT count(*) AS total\nFROM ${t};` },
    {
      label: "Inserir",
      sql: cols.length
        ? `INSERT INTO ${t} (${cols.map((c) => quote(kind, c.name)).join(", ")})\nVALUES (${cols.map(() => "'...'").join(", ")});`
        : `INSERT INTO ${t} (coluna)\nVALUES ('valor');`,
    },
    { label: "Atualizar", sql: `UPDATE ${t}\nSET coluna = 'novo valor'\nWHERE id = 1;` },
    { label: "Adicionar coluna", sql: mysql ? `ALTER TABLE ${t}\nADD COLUMN telefone VARCHAR(20);` : `ALTER TABLE ${t}\nADD COLUMN telefone text;` },
    {
      label: "Criar tabela",
      sql: mysql
        ? "CREATE TABLE produtos (\n  id BIGINT AUTO_INCREMENT PRIMARY KEY,\n  nome VARCHAR(255) NOT NULL,\n  preco DECIMAL(12,2),\n  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP\n);"
        : "CREATE TABLE produtos (\n  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  nome text NOT NULL,\n  preco numeric(12,2),\n  criado_em timestamptz DEFAULT now()\n);",
    },
  ];
}

/** SQL Editor (Redis: one command per line). Ctrl+Enter runs everything in the box. */
export function SqlEditor({ distro, containerId, kind, table, columns, onChanged }: Props) {
  const redis = kind === "redis";
  const [sql, setSql] = useState(() => (redis ? "KEYS *" : table ? `SELECT *\nFROM ${quote(kind, table)}\nLIMIT 100;` : "SELECT now();"));
  const [running, setRunning] = useState(false);
  const [result, setResult] = useState<{ data: DbQueryResult; ms: number } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const box = useRef<HTMLTextAreaElement>(null);

  const run = async () => {
    if (running || !sql.trim()) return;
    setRunning(true);
    setError(null);
    const started = performance.now();
    try {
      const data = await dbExecuteSql(distro, containerId, sql);
      setResult({ data, ms: Math.round(performance.now() - started) });
    } catch (err) {
      setResult(null);
      setError(errorMessage(err));
    } finally {
      setRunning(false);
      onChanged();
    }
  };

  return (
    <div className="flex min-h-0 flex-1 flex-col">
      <div className="space-y-2.5 border-b border-zinc-800 p-4">
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="mr-1 text-[11px] text-zinc-500">Modelos:</span>
          {templates(kind, table, columns).map((t) => (
            <button
              key={t.label}
              type="button"
              onClick={() => {
                setSql(t.sql);
                box.current?.focus();
              }}
              className="rounded-full border border-zinc-800 px-2.5 py-0.5 text-[11px] text-zinc-400 transition-colors hover:border-zinc-600 hover:text-zinc-100"
            >
              {t.label}
            </button>
          ))}
        </div>
        <textarea
          ref={box}
          value={sql}
          onChange={(e) => setSql(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) {
              e.preventDefault();
              void run();
            }
          }}
          spellCheck={false}
          rows={8}
          className="w-full resize-y rounded-lg border border-zinc-800 bg-void p-3 font-mono text-xs leading-relaxed text-zinc-100 focus:border-zinc-600 focus:outline-none"
          placeholder={redis ? "Um comando por linha, ex.: GET minha-chave" : "SELECT * FROM minha_tabela;"}
        />
        <div className="flex items-center gap-2">
          <button type="button" onClick={run} disabled={running || !sql.trim()} className={`${BTN_PRIMARY} whitespace-nowrap`}>
            {running ? <Loader2 className="size-3.5 animate-spin" /> : <Play className="size-3.5" />}
            {redis ? "Executar" : "Executar SQL"}
            <span className="font-mono text-[10px] opacity-60">Ctrl+Enter</span>
          </button>
          {!redis && (
            <span className="flex items-center gap-1.5 text-[11px] text-zinc-500">
              Vários comandos separados por <span className="font-mono">;</span> rodam em ordem
              <InfoTip>
                Cada comando é salvo na hora (não há “desfazer”). O resultado mostrado é o do último comando que devolve linhas. Mostramos até
                1000 linhas.
              </InfoTip>
            </span>
          )}
          <span className="flex-1" />
          {result && (
            <button type="button" onClick={() => setResult(null)} className={`${BTN_GHOST} whitespace-nowrap`}>
              Limpar resultado
            </button>
          )}
        </div>
      </div>

      <div className="min-h-0 flex-1 overflow-auto">
        {error && (
          <div className="p-4">
            <ErrorBox>{error}</ErrorBox>
          </div>
        )}
        {result && <ResultView result={result.data} ms={result.ms} />}
        {!result && !error && (
          <p className="p-4 text-xs text-zinc-600">O resultado aparece aqui.</p>
        )}
      </div>
    </div>
  );
}

function ResultView({ result, ms }: { result: DbQueryResult; ms: number }) {
  if (result.columns.length === 0) {
    return (
      <p className="flex items-center gap-2 p-4 text-xs text-zinc-300">
        <CheckCircle2 className="size-4 text-emerald-400" />
        {result.statements === 1 ? "Comando executado" : `${result.statements} comandos executados`}
        {result.rowsAffected !== null && result.rowsAffected >= 0 && ` · ${result.rowsAffected} ${result.rowsAffected === 1 ? "linha afetada" : "linhas afetadas"}`}
        <span className="font-mono text-zinc-600">{ms} ms</span>
      </p>
    );
  }
  return (
    <div>
      <div className="flex items-center gap-2 px-4 py-2 text-[11px] text-zinc-500">
        <CheckCircle2 className="size-3.5 text-emerald-400" />
        {result.rows.length} {result.rows.length === 1 ? "linha" : "linhas"}
        {result.truncated && " (mostrando as primeiras 1000)"}
        <span className="font-mono text-zinc-600">{ms} ms</span>
      </div>
      <table className="w-max min-w-full border-collapse text-xs">
        <thead className="sticky top-0 bg-zinc-900">
          <tr>
            {result.columns.map((c, i) => (
              <th key={i} className="border-y border-r border-zinc-800 px-3 py-1.5 text-left font-medium whitespace-nowrap text-zinc-200">
                {c}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {result.rows.map((row, i) => (
            <tr key={i} className="hover:bg-zinc-900/60">
              {row.map((v, j) => (
                <td
                  key={j}
                  title={v && v.length > 60 ? v : undefined}
                  className={`max-w-96 truncate border-r border-b border-zinc-800/70 px-3 py-1.5 font-mono text-[11px] ${v === null ? "text-zinc-600 italic" : "text-zinc-300"}`}
                >
                  {v ?? "NULL"}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
